"""Turn the report of test/test_sh_corpora.sh into docs/compatibility/sh-corpora-failures.md
and test/sh_corpora/known-bugs.txt.

    REPORT=/tmp/report.txt sh test/test_sh_corpora.sh
    python3 -I tools/sh-corpora-doc.py /tmp/report.txt

Categories (decision 0009, gold standard rule: dash and FreeBSD sh agree => we follow):
  our bug              dash meets the corpus expectation and we do not
  interactive/jobs     needs the interactive shell or job control (milestone 2)
  deliberate           POSIX.1-2024 or strict-POSIX behaviour that dash lacks (documented
                       in docs/posix-shell-differences.md)
  shell-specific       neither dash nor we meet it: the corpus encodes yash, bash, ksh or
                       Oils behaviour, or a non-POSIX feature
  follows dash         (Oils only) we differ from the annotated expectation exactly as dash does
"""
import collections
import os
import re
import sys

report = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

INTERACTIVE = re.compile(r"interactive|spares interactive|jobs|job_spec|%%|%\+|%job|fg |bg |\bwait %|kill -15 %|PS1|PS2|prompt|\bENV\b|ps1-expand|ps2-expand", re.I)
DELIBERATE = re.compile(r"\$''|\$'|== |is alias for =|ulimit|umask|printf %q|printf -v|strftime|sh \+c|--help|-l flag|source doesn't|local|declare|array|SHELL is set|Unicode|UTF-8", re.I)
ALIAS_YASH = re.compile(r"alias")

rows = collections.defaultdict(list)
for line in open(report, encoding="utf-8", errors="replace"):
    parts = line.rstrip("\n").split("\t")
    if len(parts) < 4 or parts[0] in ("RUNNER-ERROR", "SUMMARY"):
        continue
    cat, corpus, where, name = parts[:4]
    extra = parts[4] if len(parts) > 4 else ""
    label = "our bug"
    if cat == "OTHER":
        label = "shell-specific"
    elif cat == "DASH":
        label = "follows dash"
    elif cat in ("BASH",):
        label = "shell-specific"
    elif cat == "BUG":
        if INTERACTIVE.search(name + " " + extra):
            label = "interactive/jobs"
        elif DELIBERATE.search(name):
            label = "deliberate"
    rows[corpus].append((label, where, name, extra))

counts = collections.Counter()
out = ["# sh: third-party corpora, every non-passing case", "",
       "Generated by `tools/sh-corpora-doc.py` from the report of `test/test_sh_corpora.sh` (pinned corpora, see `tools/fetch-sh-corpora.sh`). Categories are explained there. The Oils cases where we differ from the annotated expectation exactly as dash does (`follows dash`, thousands of bash/YSH-specific cases) are only counted per file, not listed.", ""]
for corpus in ("yash", "freebsd", "oils"):
    items = rows.get(corpus, [])
    out.append("## %s" % corpus)
    out.append("")
    c = collections.Counter(l for l, *_ in items)
    for k, v in sorted(c.items()):
        counts[(corpus, k)] += v
    out.append("Counts: " + ", ".join("%s %d" % (k, v) for k, v in sorted(c.items())) + ".")
    out.append("")
    byfile = collections.defaultdict(collections.Counter)
    for label, where, name, extra in items:
        if label == "follows dash":
            byfile[where][label] += 1
    if byfile:
        out.append("Follows dash, per file: " + ", ".join("%s %d" % (f, n["follows dash"]) for f, n in sorted(byfile.items())) + ".")
        out.append("")
    out.append("| Category | File | Case |")
    out.append("|---|---|---|")
    for label, where, name, extra in sorted(items):
        if label == "follows dash":
            continue
        out.append("| %s | %s | %s |" % (label, where, name.replace("|", "\\|")))
    out.append("")
with open(os.path.join(root, "docs/compatibility/sh-corpora-failures.md"), "w") as f:
    f.write("\n".join(out))

with open(os.path.join(root, "test/sh_corpora/known-bugs.txt"), "w") as f:
    for line in open(report, encoding="utf-8", errors="replace"):
        p = line.rstrip("\n").split("\t")
        if p and p[0] == "BUG":
            f.write("\t".join(p[:3] if p[1] == "freebsd" else p[:4]) + "\n")
print(dict(counts))
